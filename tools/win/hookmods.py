# Writes the C++ list of which mod each hooks.def hook belongs to (the shared source file that defines
# rbm_hook_<name> or rbm_<name>; core files by their own name), for core/image_win.cpp.
# A source can name hooks its mod does without on Windows in a comment, `// windows-optional: name name ...`:
# those belong to no mod, so the mod stays on without them.
#   python3 -I tools/win/hookmods.py <repo> > hookmods.cpp
# The edition (docs/editions.md) is RBM_EDITION's: full (default) adds private/mods/; a tree without private/ is public.
import sys, os, re, glob
repo = sys.argv[1]
EDITION = os.environ.get('RBM_EDITION', 'full') if os.path.isdir(os.path.join(repo, 'private')) else 'public'
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'build'))
import hooksdef  # (hooks.def as this edition's build reads it)
hooks = re.findall(r'^HOOK\((\w+),', hooksdef.text(repo, EDITION), re.M)
srcs = [f for d in ('core', 'mods', 'engines') + (('private/mods',) if EDITION == 'full' else ()) for f in glob.glob(os.path.join(repo, d, '*.cpp')) if not f.endswith(('_mac.cpp', '_win.cpp'))]
text = {f: open(f).read() for f in srcs}
def mod(f):
    m = os.path.basename(f).split('.')[0]
    return m[:-6] if m.endswith('_panel') else m
optional = {n for t in text.values() for line in re.findall(r'//\s*windows-optional:([^\n]*)', t) for n in line.split()}
out = []
for h in hooks:
    if h in optional:
        out.append('    "",  // %s (optional on Windows)' % h); continue
    pat = re.compile(r'\b(rbm_hook_%s|rbm_%s)\s*\(|RBM_ORIG\(%s\b|\b[A-Z_]*HOOK[A-Z_]*\(%s\b' % (h, h, h, h))
    fs = sorted({mod(f) for f, t in text.items() if pat.search(t)})
    if not fs:  # defined by a macro (e.g. rbm_hook_column_index##n): the file naming the hook's stem
        stem = re.sub(r'\d+$', '', h)
        fs = sorted({mod(f) for f, t in text.items() if re.search(r'rbm_hook_%s##' % stem, t)})
    out.append('    "%s",  // %s' % (fs[0] if fs else '', h))
print('// generated by tools/win/hookmods.py\nextern "C" const char* const rbm_hook_mod[] = {\n' + '\n'.join(out) + '\n};')
