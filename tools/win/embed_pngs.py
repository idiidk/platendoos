# Writes a C++ header holding PNG files as byte arrays, for the Windows badge (tools/win/build.sh):
#   kChipPngs[] = {{height in pixels, bytes, size}, ...}, smallest first.
import struct, sys

print("// generated by tools/win/embed_pngs.py from mods/badge_chip.h's drawing; do not edit")
print("#pragma once")
entries = []
for i, path in enumerate(sys.argv[1:]):
    data = open(path, "rb").read()
    height = struct.unpack(">I", data[20:24])[0]  # the IHDR chunk
    print(f"static const unsigned char kChipPng{i}[] = {{")
    for o in range(0, len(data), 24):
        print("    " + ",".join(str(b) for b in data[o:o + 24]) + ",")
    print("};")
    entries.append(f"{{{height}, kChipPng{i}, sizeof kChipPng{i}}}")
print("struct ChipPng { int height; const unsigned char* bytes; unsigned size; };")
print("static const ChipPng kChipPngs[] = {" + ", ".join(entries) + "};")
