# Writes patcher_gen.h for the patcher app (patcher/): every mod with its one-line summary (README's tables) and on
# which platforms it is built, and which mod each hooks.def hook belongs to on macOS and on Windows (as
# tools/win/hookmods.py decides it for core/image_win.cpp), so the patcher can say per mod what this rekordbox has.
#   python3 -I tools/build/patcher_gen.py <repo> > patcher_gen.h
# The edition (docs/editions.md) is RBM_EDITION's: full (default) adds private/mods/; a tree without private/ is public.
import sys, os, re, glob
repo = sys.argv[1]
HAS_PRIVATE = os.path.isdir(os.path.join(repo, 'private'))
EDITION = os.environ.get('RBM_EDITION', 'full') if HAS_PRIVATE else 'public'
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hooksdef  # (hooks.def as this edition's build reads it)
hooks = re.findall(r'^HOOK\((\w+),', hooksdef.text(repo, EDITION), re.M)

def modname(f):
    m = os.path.basename(f).split('.')[0]
    for suf in ('_panel', '_mac', '_win', '_ort', '_view', '_overlay', '_backend', '_art', '_chip'):
        if m.endswith(suf): m = m[:-len(suf)]
    return m

def files(plat):
    out = []
    for d in ('core', 'mods', 'engines') + (('private/mods',) if EDITION == 'full' else ()):
        for f in glob.glob(os.path.join(repo, d, '*')):
            if not f.endswith(('.cpp', '.mm')): continue
            if plat == 'win' and (f.endswith('.mm') or '_mac.' in f): continue
            if plat == 'mac' and ('_win.' in f or '_ort.' in f or f.endswith('engines/ort.cpp')): continue
            out.append(f)
    return out

def hookmods(plat):
    text = {f: open(f).read() for f in files(plat)}
    optional = set()
    if plat == 'win':
        optional = {n for t in text.values() for line in re.findall(r'//\s*windows-optional:([^\n]*)', t) for n in line.split()}
    res = []
    for h in hooks:
        if h in optional: res.append(''); continue
        pat = re.compile(r'\b(rbm_hook_%s|rbm_%s)\s*\(|RBM_ORIG\(%s\b|\b[A-Z_]*HOOK[A-Z_]*\(%s\b' % (h, h, h, h))
        fs = sorted({modname(f) for f, t in text.items() if pat.search(t)})
        if not fs:
            stem = re.sub(r'\d+$', '', h)
            fs = sorted({modname(f) for f, t in text.items() if re.search(r'rbm_hook_%s##' % stem, t)})
        res.append(fs[0] if fs else '')
    return res

def mods(plat):
    # a file with a "// windows-only" line has all its code under #ifdef _WIN32: no such mod on macOS
    return {modname(f) for f in files(plat) if '/mods/' in f and
            not (plat == 'mac' and re.search(r'^//\s*windows-only\s*$', open(f).read(), re.M))}

summary = {}
readmes = [os.path.join(repo, 'README.md')] + ([os.path.join(repo, 'private', 'README.md')] if EDITION == 'full' else [])
readme = '\n'.join(open(f, encoding='utf-8').read() for f in readmes if os.path.exists(f))
for name, text in re.findall(r'^\| \*\*(\w+)\*\* \| (.*?) \|\s*$', readme, re.M):
    s = re.sub(r'\*\*?|`', '', text)
    m = re.match(r'(.+?(?<!e\.g)[.!?])(\s|$)', s)
    summary[name] = (m.group(1) if m else s).strip()

# flx4 has a section of its own rather than a table row
summary.setdefault('flx4', 'Makes a Pioneer DDJ-FLX4 a four-deck controller with stems, using SHIFT combinations the FLX4 doesn\'t use itself.')
# The mods that say they haven't run on a platform yet (RBM_MOD .untested = "win" / "mac"): off there unless asked for.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import settings_parse
untested = {p: settings_parse.off_unless_asked(repo, p, EDITION) for p in ('mac', 'win')}
mac, win = mods('mac'), mods('win')
names = sorted(n for n in mac | win if n in summary)
c = lambda s: '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
print('// generated by tools/build/patcher_gen.py')
print('#pragma once')
print('namespace patcher::gen {')
print('static const char* const kEdition = %s;' % c(EDITION))
print('struct Mod { const char* name; const char* summary; bool mac, win; bool untestedMac, untestedWin; };')
print('static const Mod kMods[] = {')
b = lambda x: 'true' if x else 'false'
for n in names: print('    {%s, %s, %s, %s, %s, %s},' % (c(n), c(summary[n]), b(n in mac), b(n in win), b(n in untested['mac']), b(n in untested['win'])))
print('};')
for plat in ('mac', 'win'):
    print('static const char* const kHookMod_%s[] = {%s};' % (plat, ', '.join(c(m) for m in hookmods(plat))))
print('static const char* const kHookName[] = {%s};' % ', '.join(c(h) for h in hooks))
print('static const int kHooks = %d;' % len(hooks))
print('}  // namespace patcher::gen')
